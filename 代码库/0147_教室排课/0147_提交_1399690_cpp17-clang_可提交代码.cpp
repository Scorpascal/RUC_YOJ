#include <stdio.h> // 引入标准输入输出库，提供输入输出函数（如printf、scanf）

int j[8] = {120, 40, 85, 50, 100, 140, 70, 100}; // 定义一个长度为8的整型数组j，存储8个数值，代表可选的资源或物品的属性（如重量、容量等）

int n[4], t[4], used[8], a = 0; 
// n[4]：长度为4的整型数组，存储用户输入的4个需求值
// t[4]：长度为4的整型数组，存储当前方案中选中的物品编号（下标+1）
// used[8]：长度为8的整型数组，标记每个物品是否已被选用（0表示未选，1表示已选）
// a：整型变量，统计满足条件的方案数量

void dfs(int depth) { // 定义一个递归函数，参数depth表示当前递归的深度（即已选物品的数量）
    if (depth == 4) { // 如果已经选了4个物品（达到需求数量）
        printf("%d %d %d %d\n", t[0], t[1], t[2], t[3]); // 输出当前方案中选中的4个物品编号
        a++; // 满足条件的方案数量加1
        return; // 结束本次递归
    }
    for (int i = 0; i < 8; i++) { // 遍历所有8个物品
        if (!used[i] && n[depth] <= j[i]) { 
            // 如果第i个物品未被选用，且当前需求n[depth]小于等于物品属性j[i]，则可以选用该物品
            used[i] = 1; // 标记第i个物品已被选用
            t[depth] = i + 1; // 记录选中的物品编号（编号从1开始）
            dfs(depth + 1); // 递归，继续选择下一个物品
            used[i] = 0; // 回溯，取消第i个物品的选用标记，尝试其他组合
        }
    }
}

int main(void) { // 主函数入口
    for (int i = 0; i < 4; i++) { // 循环4次
        scanf("%d", n + i); // 从标准输入读取4个整数，分别存入n[0]~n[3]，表示4个需求
    }
    for (int i = 0; i < 8; i++) used[i] = 0; // 初始化used数组，所有物品都未被选用
    dfs(0); // 从深度0开始递归搜索所有满足条件的组合
    if (a == 0) printf("-1\n"); // 如果没有任何满足条件的方案，输出-1
    return 0; // 程序正常结束
}